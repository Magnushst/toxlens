#!/usr/bin/env python3
"""
End-to-end published benchmark retraining for the ToxLens architecture.

This runner performs the experiment required for a defensible architecture
comparison:

1. Download the exact public development and held-out test folds from a
   published benchmark.
2. Keep the published test fold untouched.
3. Split only the published development fold into 90% train / 10% validation.
4. Recompute the complete ToxLens molecular representation from SMILES.
5. Train a fresh ToxLens model, selecting the checkpoint and decision threshold
   using validation data only.
6. Evaluate the selected checkpoint once on the published test fold.
7. Repeat over independent seeds and compare mean test AUROC with published
   methods evaluated by the same benchmark protocol.

The original DeepTox/Tox21 Challenge is intentionally excluded because it has
already been evaluated elsewhere in this project. MoleculeNet Tox21 is also
excluded: the MoleculeNet paper used random Tox21 splits, so the scaffold split
previously generated by this file was not an exact reproduction of that paper.

Included exact benchmarks
-------------------------
* TDC.AMES
* TDC.hERG
* TDC.DILI

TDC is a peer-reviewed benchmark (NeurIPS 2021 Datasets and Benchmarks). Its
benchmark-group loader provides the exact public scaffold-held-out test fold.
The development fold is split locally into 90%/10% train/validation without
ever using the test labels for training, checkpoint selection, threshold
selection, or calibration.

Run the full experiment from Git Bash:

    python.exe -u fetch_external_benchmarks.py

Run only data preparation and split audits:

    python.exe -u fetch_external_benchmarks.py --prepare-only

Run one benchmark and one seed:

    python.exe -u fetch_external_benchmarks.py \
      --benchmarks tdc_ames \
      --seeds 42

Outputs are written below ``published_benchmark_runs/`` by default.
"""

