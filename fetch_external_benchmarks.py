def log(message: str) -> None:
    print(f"[PublishedBenchmark] {message}", flush=True)


def parse_csv_list(value: str) -> List[str]:
    return [item.strip() for item in value.split(",") if item.strip()]


def json_ready(value: Any) -> Any:
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, Mapping):
        return {str(k): json_ready(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [json_ready(v) for v in value]
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        return float(value)
    if isinstance(value, float) and not math.isfinite(value):
        return None
    return value


def write_json(path: Path, payload: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(json_ready(payload), indent=2), encoding="utf-8")


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def dataframe_digest(df: pd.DataFrame, columns: Sequence[str]) -> str:
    stable = df.loc[:, list(columns)].copy()
    return sha256_bytes(stable.to_csv(index=False, lineterminator="\n").encode("utf-8"))


def import_module_from_path(module_name: str, path: Path):
    if not path.is_file():
        raise FileNotFoundError(f"Required module not found: {path}")
    spec = importlib.util.spec_from_file_location(module_name, str(path))
    if spec is None or spec.loader is None:
        raise ImportError(f"Could not construct import spec for {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    spec.loader.exec_module(module)
    return module


def build_rdkit_canonicaliser():
    """Return a fast, deterministic identity canonicaliser for split audits."""
    from rdkit import Chem
    from rdkit import RDLogger
    from rdkit.Chem.MolStandardize import rdMolStandardize

    RDLogger.DisableLog("rdApp.warning")
    largest_fragment = rdMolStandardize.LargestFragmentChooser()
    uncharger = rdMolStandardize.Uncharger()

    @functools.lru_cache(maxsize=None)
    def _canonicalise(smiles: str) -> str | None:
        try:
            mol = Chem.MolFromSmiles(str(smiles))
            if mol is None:
                return None
            mol = largest_fragment.choose(mol)
            mol = uncharger.uncharge(mol)
            Chem.SanitizeMol(mol)
            return Chem.MolToSmiles(mol, canonical=True, isomericSmiles=True)
        except Exception:
            return None

    return _canonicalise


def normalise_tdc_frame(
    frame: pd.DataFrame,
    spec: BenchmarkSpec,
    published_fold: str,
) -> pd.DataFrame:
    smiles_col = "Drug" if "Drug" in frame.columns else "smiles"
    if smiles_col not in frame.columns or "Y" not in frame.columns:
        raise RuntimeError(
            f"TDC {spec.tdc_name} returned unexpected columns: {list(frame.columns)}"
        )

    source_ids = (
        frame["Drug_ID"].fillna("").astype(str)
        if "Drug_ID" in frame.columns
        else pd.Series([""] * len(frame), index=frame.index, dtype=str)
    )
    smiles = frame[smiles_col].astype(str)
    labels = pd.to_numeric(frame["Y"], errors="coerce")
    row_ids = [
        hashlib.sha256(
            (
                f"{spec.key}|{published_fold}|{position}|{source_id}|"
                f"{smiles_value}|{label_value}"
            ).encode("utf-8")
        ).hexdigest()[:24]
        for position, (source_id, smiles_value, label_value) in enumerate(
            zip(source_ids, smiles, labels)
        )
    ]
    out = pd.DataFrame(
        {
            "benchmark_row_id": row_ids,
            "source_id": source_ids.to_numpy(),
            "smiles": smiles.to_numpy(),
            spec.task_name: labels.to_numpy(),
            "published_fold": published_fold,
        }
    )
    out = out.dropna(subset=[spec.task_name]).reset_index(drop=True)
    observed = set(out[spec.task_name].astype(float).unique().tolist())
    if not observed.issubset({0.0, 1.0}):
        raise RuntimeError(
            f"{spec.key} is not binary classification. Observed labels: {sorted(observed)[:10]}"
        )
    out[spec.task_name] = out[spec.task_name].astype(np.float32)
    if out["benchmark_row_id"].duplicated().any():
        raise RuntimeError(f"Failed to construct unique row IDs for {spec.key}.")
    return out


def fetch_exact_published_folds(
    spec: BenchmarkSpec,
    raw_root: Path,
    benchmark_dir: Path,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    try:
        from tdc.benchmark_group import admet_group
    except Exception as exc:
        raise RuntimeError(
            "PyTDC is required. Install it in the deep_tox environment with "
            "`pip install PyTDC`."
        ) from exc

    group = admet_group(path=str(raw_root))
    benchmark = group.get(spec.tdc_name)
    development = normalise_tdc_frame(
        benchmark["train_val"], spec, published_fold="development"
    )
    test = normalise_tdc_frame(benchmark["test"], spec, published_fold="test")

    benchmark_dir.mkdir(parents=True, exist_ok=True)
    development_path = benchmark_dir / "published_development.csv"
    test_path = benchmark_dir / "published_test.csv"
    development.to_csv(development_path, index=False)
    test.to_csv(test_path, index=False)

    log(
        f"{spec.key}: exact TDC folds fetched; development={len(development)}, "
        f"untouched_test={len(test)}."
    )
    return development, test


def canonical_groups(frame: pd.DataFrame, canonicalise) -> np.ndarray:
    groups: List[str] = []
    failed = 0
    for idx, smiles in enumerate(frame["smiles"].astype(str)):
        try:
            canonical = canonicalise(smiles)
        except Exception:
            canonical = None
        if canonical:
            groups.append(str(canonical))
        else:
            groups.append(f"__unparseable_{idx}")
            failed += 1
    if failed:
        log(f"Canonicalisation failed for {failed} development rows; kept as unique groups.")
    return np.asarray(groups, dtype=object)


def split_development_90_10(
    development: pd.DataFrame,
    spec: BenchmarkSpec,
    seed: int,
    canonicalise,
) -> pd.DataFrame:
    labels = development[spec.task_name].astype(int).to_numpy()
    groups = canonical_groups(development, canonicalise)
    indices = np.arange(len(development))

    try:
        splitter = StratifiedGroupKFold(n_splits=10, shuffle=True, random_state=seed)
        train_idx, val_idx = next(splitter.split(indices, labels, groups))
        split_method = "StratifiedGroupKFold(n_splits=10)"
    except Exception as exc:
        log(f"Grouped split failed for {spec.key} seed={seed} ({exc}); using stratified rows.")
        splitter = StratifiedShuffleSplit(n_splits=1, test_size=0.10, random_state=seed)
        train_idx, val_idx = next(splitter.split(indices, labels))
        split_method = "StratifiedShuffleSplit(test_size=0.10)"

    prepared = development.copy()
    prepared["benchmark_split"] = "train"
    prepared.loc[val_idx, "benchmark_split"] = "val"
    prepared["split_seed"] = int(seed)
    prepared["split_method"] = split_method

    train_labels = prepared.loc[prepared["benchmark_split"] == "train", spec.task_name]
    val_labels = prepared.loc[prepared["benchmark_split"] == "val", spec.task_name]
    for fold_name, fold_labels in (("train", train_labels), ("validation", val_labels)):
        if fold_labels.nunique() != 2:
            raise RuntimeError(
                f"{spec.key} seed={seed} {fold_name} fold does not contain both classes."
            )
    return prepared


def exact_identity_overlap(left: pd.DataFrame, right: pd.DataFrame, canonicalise) -> int:
    def _set(frame: pd.DataFrame) -> set[str]:
        values = set()
        for smiles in frame["smiles"].astype(str):
            try:
                canonical = canonicalise(smiles)
            except Exception:
                canonical = None
            if canonical:
                values.add(str(canonical))
        return values

    return len(_set(left) & _set(right))


def fold_statistics(frame: pd.DataFrame, spec: BenchmarkSpec, fold: str) -> Dict[str, Any]:
    labels = frame[spec.task_name].astype(int)
    n_pos = int((labels == 1).sum())
    n_neg = int((labels == 0).sum())
    return {
        "fold": fold,
        "n": int(len(frame)),
        "n_positive": n_pos,
        "n_negative": n_neg,
        "positive_fraction": float(n_pos / len(frame)) if len(frame) else float("nan"),
    }


def prepare_seed_split(
    development: pd.DataFrame,
    test: pd.DataFrame,
    spec: BenchmarkSpec,
    seed: int,
    benchmark_dir: Path,
    canonicalise,
) -> tuple[pd.DataFrame, Dict[str, Any]]:
    split_development = split_development_90_10(
        development=development,
        spec=spec,
        seed=seed,
        canonicalise=canonicalise,
    )
    test_with_split = test.copy()
    test_with_split["benchmark_split"] = "test"
    test_with_split["split_seed"] = int(seed)
    test_with_split["split_method"] = "published untouched test fold"
    prepared = pd.concat([split_development, test_with_split], ignore_index=True)

    seed_dir = benchmark_dir / "splits" / f"seed_{seed}"
    seed_dir.mkdir(parents=True, exist_ok=True)
    for fold, selector in (
        ("train", prepared["benchmark_split"] == "train"),
        ("validation", prepared["benchmark_split"] == "val"),
        ("test", prepared["benchmark_split"] == "test"),
    ):
        prepared.loc[selector].to_csv(seed_dir / f"{fold}.csv", index=False)
    prepared.to_csv(seed_dir / "all_rows.csv", index=False)

    train = prepared.loc[prepared["benchmark_split"] == "train"]
    val = prepared.loc[prepared["benchmark_split"] == "val"]
    held_out = prepared.loc[prepared["benchmark_split"] == "test"]
    row_id_overlap = {
        "train_validation": int(
            len(set(train["benchmark_row_id"]) & set(val["benchmark_row_id"]))
        ),
        "development_test": int(
            len(
                set(pd.concat([train, val])["benchmark_row_id"])
                & set(held_out["benchmark_row_id"])
            )
        ),
    }
    identity_overlap = {
        "train_validation": exact_identity_overlap(train, val, canonicalise),
        "development_test": exact_identity_overlap(
            pd.concat([train, val]), held_out, canonicalise
        ),
    }
    if row_id_overlap["train_validation"] or row_id_overlap["development_test"]:
        raise RuntimeError(f"Row-ID leakage detected for {spec.key} seed={seed}.")
    if identity_overlap["train_validation"]:
        raise RuntimeError(
            f"Canonical molecule leakage between train and validation for "
            f"{spec.key} seed={seed}."
        )

    audit = {
        "benchmark": spec.key,
        "seed": int(seed),
        "requested_development_ratio": {"train": 0.90, "validation": 0.10},
        "actual_development_ratio": {
            "train": float(len(train) / len(development)),
            "validation": float(len(val) / len(development)),
        },
        "fold_statistics": [
            fold_statistics(train, spec, "train"),
            fold_statistics(val, spec, "validation"),
            fold_statistics(held_out, spec, "test"),
        ],
        "row_id_overlap": row_id_overlap,
        "canonical_identity_overlap": identity_overlap,
        "test_fold_modified": False,
        "prepared_digest": dataframe_digest(
            prepared,
            ["benchmark_row_id", "smiles", spec.task_name, "benchmark_split"],
        ),
    }
    write_json(seed_dir / "split_audit.json", audit)
    return prepared, audit


def task_config(task_name: str) -> Dict[str, Dict[str, Any]]:
    return {
        task_name: {
            "type": "classification",
            "category": "primary",
            "source": "published_external_benchmark",
            "targets": [task_name],
        }
    }


def build_or_load_feature_bundle(
    dt,
    spec: BenchmarkSpec,
    prepared: pd.DataFrame,
    benchmark_dir: Path,
    deep_tox_path: Path,
    force_refeaturize: bool,
) -> Dict[str, Any]:
    feature_dir = benchmark_dir / "features"
    feature_dir.mkdir(parents=True, exist_ok=True)
    bundle_path = feature_dir / "toxlens_feature_bundle.pkl"
    metadata_path = feature_dir / "toxlens_feature_bundle.json"
    dataset_hash = dataframe_digest(
        prepared.sort_values("benchmark_row_id"),
        ["benchmark_row_id", "smiles", spec.task_name],
    )
    expected_metadata = {
        "benchmark": spec.key,
        "task_name": spec.task_name,
        "dataset_digest": dataset_hash,
        "deep_tox_sha256": sha256_file(deep_tox_path),
        "graph_feature_policy_version": int(dt.GRAPH_FEATURE_POLICY_VERSION),
    }

    if bundle_path.exists() and metadata_path.exists() and not force_refeaturize:
        existing = json.loads(metadata_path.read_text(encoding="utf-8"))
        if all(existing.get(key) == value for key, value in expected_metadata.items()):
            log(f"{spec.key}: loading verified feature bundle {bundle_path}.")
            return joblib.load(bundle_path)
        log(f"{spec.key}: feature metadata changed; rebuilding all molecular features.")

    log(f"{spec.key}: computing complete ToxLens representation from raw SMILES.")
    old_task_config = dt.TASK_CONFIG
    old_focus_weights = dt.PRIMARY_TASK_FOCUS_WEIGHTS
    try:
        dt.TASK_CONFIG = task_config(spec.task_name)
        dt.PRIMARY_TASK_FOCUS_WEIGHTS = {spec.task_name: 1.0}
        (
            train_graphs,
            val_graphs,
            test_graphs,
            train_df,
            val_df,
            test_df,
        ) = dt.molecular_graphs_representation(
            prepared,
            [spec.task_name],
            split_column="benchmark_split",
            make_split_figures=False,
            artifact_dir=str(feature_dir),
        )
    finally:
        dt.TASK_CONFIG = old_task_config
        dt.PRIMARY_TASK_FOCUS_WEIGHTS = old_focus_weights

    all_graphs = train_graphs + val_graphs + test_graphs
    graph_by_id: Dict[str, Any] = {}
    for graph in all_graphs:
        row_id = getattr(graph, "benchmark_row_id", None)
        if row_id is None:
            raise RuntimeError(
                "Feature graph lacks benchmark_row_id. Re-run with the updated deep_tox.py."
            )
        row_id = str(row_id)
        if row_id in graph_by_id:
            raise RuntimeError(f"Duplicate graph row ID after featurisation: {row_id}")
        graph_by_id[row_id] = graph

    requested_ids = set(prepared["benchmark_row_id"].astype(str))
    retained_ids = set(graph_by_id)
    dropped_ids = sorted(requested_ids - retained_ids)
    bundle = {
        "metadata": {
            **expected_metadata,
            "n_requested": len(requested_ids),
            "n_featurised": len(retained_ids),
            "n_dropped": len(dropped_ids),
            "dropped_row_ids": dropped_ids,
            "created_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        },
        "graphs_by_row_id": graph_by_id,
    }
    joblib.dump(bundle, bundle_path, compress=3)
    write_json(metadata_path, bundle["metadata"])
    log(
        f"{spec.key}: feature bundle saved; retained={len(retained_ids)}, "
        f"dropped={len(dropped_ids)}."
    )
    return bundle


def materialise_graph_split(
    prepared: pd.DataFrame,
    bundle: Mapping[str, Any],
) -> tuple[List[Any], List[Any], List[Any], pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    graph_by_id = bundle["graphs_by_row_id"]

    def _fold(name: str) -> tuple[List[Any], pd.DataFrame]:
        selector = (
            prepared["benchmark_split"] == name
            if name != "val"
            else prepared["benchmark_split"].isin(["val", "valid", "validation"])
        )
        frame = prepared.loc[selector].copy()
        keep = frame["benchmark_row_id"].astype(str).isin(graph_by_id)
        frame = frame.loc[keep].reset_index(drop=True)
        graphs = [graph_by_id[row_id] for row_id in frame["benchmark_row_id"].astype(str)]
        return graphs, frame

    train_graphs, train_df = _fold("train")
    val_graphs, val_df = _fold("val")
    test_graphs, test_df = _fold("test")
    return train_graphs, val_graphs, test_graphs, train_df, val_df, test_df


def run_signature(
    spec: BenchmarkSpec,
    seed: int,
    prepared_digest: str,
    deep_tox_path: Path,
    args: argparse.Namespace,
) -> str:
    payload = {
        "benchmark": spec.key,
        "seed": int(seed),
        "prepared_digest": prepared_digest,
        "deep_tox_sha256": sha256_file(deep_tox_path),
        "max_epochs": int(args.max_epochs),
        "min_epochs": int(args.min_epochs),
        "patience": int(args.patience),
        "accelerator": args.device,
    }
    return sha256_bytes(json.dumps(payload, sort_keys=True).encode("utf-8"))


def read_seed_metrics(metrics_csv: Path) -> Dict[str, Any]:
    if not metrics_csv.is_file():
        raise FileNotFoundError(f"Expected test metric file was not written: {metrics_csv}")
    frame = pd.read_csv(metrics_csv)
    if len(frame) != 1:
        raise RuntimeError(
            f"Expected one task row in {metrics_csv}; found {len(frame)} rows."
        )
    row = frame.iloc[0].to_dict()
    keep = (
        "task_name",
        "thr",
        "mcc",
        "mcc_lo",
        "mcc_hi",
        "roc_auc",
        "roc_lo",
        "roc_hi",
        "pr_auc",
        "pr_lo",
        "pr_hi",
        "f1",
        "precision",
        "recall",
        "specificity",
        "acc",
        "bal_acc",
        "brier",
        "ece",
        "kappa",
        "log_loss",
    )
    return {key: row.get(key) for key in keep}


def train_one_seed(
    dt,
    spec: BenchmarkSpec,
    seed: int,
    prepared: pd.DataFrame,
    audit: Mapping[str, Any],
    bundle: Mapping[str, Any],
    benchmark_dir: Path,
    deep_tox_path: Path,
    args: argparse.Namespace,
) -> Dict[str, Any]:
    run_dir = benchmark_dir / "runs" / f"seed_{seed}"
    run_dir.mkdir(parents=True, exist_ok=True)
    result_path = run_dir / "seed_result.json"
    signature = run_signature(
        spec,
        seed,
        str(audit["prepared_digest"]),
        deep_tox_path,
        args,
    )
    if result_path.exists() and not args.force_train:
        existing = json.loads(result_path.read_text(encoding="utf-8"))
        if existing.get("run_signature") == signature:
            log(f"{spec.key} seed={seed}: verified completed run found; reusing metrics.")
            return existing

    (
        train_graphs,
        val_graphs,
        test_graphs,
        train_df,
        val_df,
        test_df,
    ) = materialise_graph_split(prepared, bundle)
    if not train_graphs or not val_graphs or not test_graphs:
        raise RuntimeError(
            f"{spec.key} seed={seed}: empty graph fold after featurisation."
        )

    old_task_config = dt.TASK_CONFIG
    old_focus_weights = dt.PRIMARY_TASK_FOCUS_WEIGHTS
    old_allow_test = dt.ALLOW_TEST_EVALUATION
    try:
        dt.TASK_CONFIG = task_config(spec.task_name)
        dt.PRIMARY_TASK_FOCUS_WEIGHTS = {spec.task_name: 1.0}
        dt.ALLOW_TEST_EVALUATION = True
        log(
            f"{spec.key} seed={seed}: training fresh model on "
            f"{len(train_graphs)}/{len(val_graphs)}/{len(test_graphs)} "
            "train/validation/test molecules."
        )
        model_result = dt.geometry_gnn_classification(
            train_graphs,
            val_graphs,
            test_graphs,
            [spec.task_name],
            val_df,
            test_df,
            run_label=f"toxlens_{spec.key}_seed{seed}",
            out_dir_cls=str(run_dir),
            run_external_audit=False,
            seed=seed,
            max_epochs=args.max_epochs,
            min_epochs=args.min_epochs,
            early_stopping_patience=args.patience,
            checkpoint_root=str(args.checkpoint_dir),
            run_posthoc_uncertainty=False,
            accelerator=args.device,
        )
    finally:
        dt.TASK_CONFIG = old_task_config
        dt.PRIMARY_TASK_FOCUS_WEIGHTS = old_focus_weights
        dt.ALLOW_TEST_EVALUATION = old_allow_test

    per_task_metrics = read_seed_metrics(run_dir / "test_metrics_with_ci.csv")
    result = {
        "run_signature": signature,
        "benchmark": spec.key,
        "task_name": spec.task_name,
        "seed": int(seed),
        "n_train": len(train_graphs),
        "n_validation": len(val_graphs),
        "n_test": len(test_graphs),
        "best_checkpoint": model_result.get("best_checkpoint"),
        "best_val_mcc": model_result.get("best_val_mcc"),
        **per_task_metrics,
    }
    write_json(result_path, result)
    return result


def summarise_benchmark(
    spec: BenchmarkSpec,
    seed_results: Sequence[Mapping[str, Any]],
    audits: Sequence[Mapping[str, Any]],
    benchmark_dir: Path,
) -> tuple[Dict[str, Any], pd.DataFrame]:
    result_frame = pd.DataFrame(seed_results)
    result_frame.to_csv(benchmark_dir / "per_seed_test_metrics.csv", index=False)
    metric_names = [
        "roc_auc",
        "pr_auc",
        "mcc",
        "f1",
        "precision",
        "recall",
        "specificity",
        "acc",
        "bal_acc",
        "brier",
        "ece",
        "kappa",
        "log_loss",
    ]
    development_test_overlap = max(
        int(audit["canonical_identity_overlap"]["development_test"])
        for audit in audits
    )
    clean_claim_eligible = development_test_overlap == 0
    summary: Dict[str, Any] = {
        "benchmark": spec.key,
        "task_name": spec.task_name,
        "n_seeds": int(len(result_frame)),
        "seeds": result_frame["seed"].astype(int).tolist(),
        "published_test_fold": "TDC benchmark-group scaffold-held-out test fold",
        "primary_comparison_metric": "AUROC",
        "development_test_canonical_overlap": development_test_overlap,
        "clean_claim_eligible": clean_claim_eligible,
    }
    for metric in metric_names:
        values = pd.to_numeric(result_frame[metric], errors="coerce")
        summary[f"{metric}_mean"] = float(values.mean())
        summary[f"{metric}_std"] = float(values.std(ddof=1)) if len(values) > 1 else 0.0

    comparison_rows = []
    for comparator in spec.comparators:
        delta = summary["roc_auc_mean"] - comparator.auroc_mean
        comparison_rows.append(
            {
                "benchmark": spec.key,
                "our_model": "ToxLens architecture retrained from scratch",
                "our_auroc_mean": summary["roc_auc_mean"],
                "our_auroc_std_across_seeds": summary["roc_auc_std"],
                "published_model": comparator.model,
                "published_auroc_mean": comparator.auroc_mean,
                "published_auroc_std": comparator.auroc_std,
                "point_estimate_delta": delta,
                "higher_point_estimate": bool(delta > 0),
                "development_test_canonical_overlap": development_test_overlap,
                "clean_claim_eligible": clean_claim_eligible,
                "paper_citation": comparator.paper_citation,
                "paper_url": comparator.paper_url,
                "benchmark_score_source": spec.leaderboard_url,
                "claim_note": (
                    (
                        "A positive delta means a higher official-test AUROC point "
                        "estimate. It is not, by itself, a statistical superiority "
                        "claim because paired comparator predictions are unavailable."
                    )
                    if clean_claim_eligible
                    else (
                        "Protocol-reproduction result only: the official published "
                        f"fold contains {development_test_overlap} canonical "
                        "development/test molecular overlaps. Do not use this row as "
                        "a clean superiority claim."
                    )
                ),
            }
        )
    comparison = pd.DataFrame(comparison_rows)
    comparison.to_csv(benchmark_dir / "published_method_comparison.csv", index=False)
    write_json(benchmark_dir / "benchmark_summary.json", summary)
    return summary, comparison


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Fetch exact published toxicity benchmark folds, split only the "
            "development fold 90/10, re-featurise, retrain ToxLens, and evaluate "
            "the untouched published test fold."
        )
    )
    parser.add_argument(
        "--benchmarks",
        default="tdc_ames,tdc_herg,tdc_dili",
        help=f"Comma-separated benchmark keys. Available: {','.join(BENCHMARKS)}",
    )
    parser.add_argument(
        "--seeds",
        default="1,2,3,4,5",
        help="Comma-separated training/validation split and model seeds.",
    )
    parser.add_argument("--deep-tox", type=Path, default=Path("deep_tox.py"))
    parser.add_argument(
        "--output-dir", type=Path, default=Path("published_benchmark_runs")
    )
    parser.add_argument(
        "--raw-data-dir",
        type=Path,
        default=Path("published_benchmark_runs") / "tdc_raw",
    )
    parser.add_argument(
        "--checkpoint-dir",
        type=Path,
        default=Path(r"C:\Users\magnu\Desktop\models\published_benchmarks"),
    )
    parser.add_argument("--max-epochs", type=int, default=350)
    parser.add_argument("--min-epochs", type=int, default=40)
    parser.add_argument("--patience", type=int, default=20)
    parser.add_argument(
        "--device",
        choices=("auto", "gpu", "cuda", "cpu"),
        default="auto",
        help="Training accelerator. auto uses CUDA when available.",
    )
    parser.add_argument(
        "--prepare-only",
        action="store_true",
        help="Fetch exact folds and write audited 90/10 splits without featurising/training.",
    )
